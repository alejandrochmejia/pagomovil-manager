CREATE OR REPLACE FUNCTION public.get_scan_stats(p_empresa_id bigint)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE
  result jsonb; v_total bigint; v_failed bigint; v_avg_ms numeric; v_corrected bigint;
BEGIN
  SELECT COUNT(*) INTO v_total FROM scan_logs WHERE empresa_id = p_empresa_id;
  IF v_total = 0 THEN
    RETURN jsonb_build_object('tasa_rechazo', 0, 'tiempo_promedio_ms', 0, 'tasa_correccion', 0, 'total_scans', 0);
  END IF;
  SELECT COUNT(*) INTO v_failed FROM scan_logs WHERE scan_status LIKE 'failed_%' AND empresa_id = p_empresa_id;
  SELECT COALESCE(AVG(EXTRACT(EPOCH FROM (scan_completed_at - scan_started_at)) * 1000), 0)
    INTO v_avg_ms FROM scan_logs WHERE scan_completed_at IS NOT NULL AND empresa_id = p_empresa_id;
  SELECT COUNT(*) INTO v_corrected FROM scan_logs
    WHERE campos_extraidos IS NOT NULL AND campos_finales IS NOT NULL
      AND campos_extraidos IS DISTINCT FROM campos_finales AND empresa_id = p_empresa_id;
  SELECT jsonb_build_object(
    'tasa_rechazo', ROUND((v_failed::numeric / v_total) * 100, 1),
    'tiempo_promedio_ms', ROUND(v_avg_ms),
    'tasa_correccion', ROUND((v_corrected::numeric / GREATEST(v_total - v_failed, 1)) * 100, 1),
    'total_scans', v_total
  ) INTO result;
  RETURN result;
END;
$function$;

CREATE OR REPLACE FUNCTION public.get_stats_breakdown(p_desde text, p_hasta text, p_group_by text, p_empresa_id bigint)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE result jsonb;
BEGIN
  IF p_group_by = 'banco' THEN
    SELECT COALESCE(jsonb_agg(row_to_json(r)), '[]'::jsonb) INTO result FROM (
      SELECT banco AS grupo, SUM(monto)::numeric AS total, COUNT(*)::int AS cantidad
      FROM pagos WHERE fecha >= p_desde::date AND fecha <= p_hasta::date AND estado = 'confirmado' AND empresa_id = p_empresa_id
      GROUP BY banco ORDER BY total DESC) r;
  ELSIF p_group_by = 'dia' THEN
    SELECT COALESCE(jsonb_agg(row_to_json(r)), '[]'::jsonb) INTO result FROM (
      SELECT fecha::text AS grupo, SUM(monto)::numeric AS total, COUNT(*)::int AS cantidad
      FROM pagos WHERE fecha >= p_desde::date AND fecha <= p_hasta::date AND estado = 'confirmado' AND empresa_id = p_empresa_id
      GROUP BY fecha ORDER BY fecha ASC) r;
  ELSIF p_group_by = 'hora' THEN
    SELECT COALESCE(jsonb_agg(row_to_json(r)), '[]'::jsonb) INTO result FROM (
      SELECT COALESCE(LEFT(hora, 2), 'N/A') AS grupo, SUM(monto)::numeric AS total, COUNT(*)::int AS cantidad
      FROM pagos WHERE fecha >= p_desde::date AND fecha <= p_hasta::date AND estado = 'confirmado' AND empresa_id = p_empresa_id
      GROUP BY COALESCE(LEFT(hora, 2), 'N/A') ORDER BY grupo ASC) r;
  ELSE
    result := '[]'::jsonb;
  END IF;
  RETURN result;
END;
$function$;

CREATE OR REPLACE FUNCTION public.get_stats_extra(p_empresa_id bigint)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare
  result jsonb;
  v_prev_month_start date := (date_trunc('month', current_date) - interval '1 month')::date;
  v_prev_month_end   date := (date_trunc('month', current_date) - interval '1 day')::date;
begin
  select jsonb_build_object(
    'total_mes_anterior', coalesce((
      select sum(monto) from pagos
      where empresa_id = p_empresa_id and estado = 'confirmado'
        and fecha >= v_prev_month_start and fecha <= v_prev_month_end), 0),
    'cantidad_mes_anterior', (
      select count(*) from pagos
      where empresa_id = p_empresa_id and estado = 'confirmado'
        and fecha >= v_prev_month_start and fecha <= v_prev_month_end),
    'ticket_promedio_historico', coalesce((
      select avg(monto) from pagos
      where empresa_id = p_empresa_id and estado = 'confirmado'), 0)
  ) into result;
  return result;
end;
$function$;

CREATE OR REPLACE FUNCTION public.get_stats_monthly(p_empresa_id bigint)
 RETURNS TABLE(mes text, total numeric, cantidad bigint) LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $function$
  with meses as (
    select generate_series(
      date_trunc('month', current_date) - interval '11 months',
      date_trunc('month', current_date),
      interval '1 month')::date as inicio)
  select to_char(m.inicio, 'YYYY-MM') as mes,
    coalesce(sum(p.monto), 0)::numeric as total,
    count(p.id)::bigint as cantidad
  from meses m
  left join public.pagos p
    on p.empresa_id = p_empresa_id and p.estado = 'confirmado'
   and p.fecha >= m.inicio and p.fecha < (m.inicio + interval '1 month')::date
  group by m.inicio order by m.inicio;
$function$;

CREATE OR REPLACE FUNCTION public.get_stats_summary(p_empresa_id bigint)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE
  result jsonb;
  v_today date := CURRENT_DATE;
  v_yesterday date := CURRENT_DATE - 1;
  v_week_start date := date_trunc('week', CURRENT_DATE)::date;
  v_prev_week_start date := (date_trunc('week', CURRENT_DATE) - interval '7 days')::date;
  v_prev_week_end date := (date_trunc('week', CURRENT_DATE) - interval '1 day')::date;
  v_month_start date := date_trunc('month', CURRENT_DATE)::date;
  v_month_end date := (date_trunc('month', CURRENT_DATE) + interval '1 month' - interval '1 day')::date;
  v_mes_actual text := to_char(CURRENT_DATE, 'YYYY-MM');
BEGIN
  SELECT jsonb_build_object(
    'total_hoy', COALESCE((SELECT SUM(monto) FROM pagos WHERE fecha = v_today AND estado = 'confirmado' AND empresa_id = p_empresa_id), 0),
    'cantidad_hoy', (SELECT COUNT(*) FROM pagos WHERE fecha = v_today AND estado = 'confirmado' AND empresa_id = p_empresa_id),
    'total_ayer', COALESCE((SELECT SUM(monto) FROM pagos WHERE fecha = v_yesterday AND estado = 'confirmado' AND empresa_id = p_empresa_id), 0),
    'cantidad_ayer', (SELECT COUNT(*) FROM pagos WHERE fecha = v_yesterday AND estado = 'confirmado' AND empresa_id = p_empresa_id),
    'total_semana', COALESCE((SELECT SUM(monto) FROM pagos WHERE fecha >= v_week_start AND fecha <= v_today AND estado = 'confirmado' AND empresa_id = p_empresa_id), 0),
    'cantidad_semana', (SELECT COUNT(*) FROM pagos WHERE fecha >= v_week_start AND fecha <= v_today AND estado = 'confirmado' AND empresa_id = p_empresa_id),
    'total_semana_anterior', COALESCE((SELECT SUM(monto) FROM pagos WHERE fecha >= v_prev_week_start AND fecha <= v_prev_week_end AND estado = 'confirmado' AND empresa_id = p_empresa_id), 0),
    'cantidad_semana_anterior', (SELECT COUNT(*) FROM pagos WHERE fecha >= v_prev_week_start AND fecha <= v_prev_week_end AND estado = 'confirmado' AND empresa_id = p_empresa_id),
    'total_mes', COALESCE((SELECT SUM(monto) FROM pagos WHERE fecha >= v_month_start AND fecha <= v_month_end AND estado = 'confirmado' AND empresa_id = p_empresa_id), 0),
    'cantidad_mes', (SELECT COUNT(*) FROM pagos WHERE fecha >= v_month_start AND fecha <= v_month_end AND estado = 'confirmado' AND empresa_id = p_empresa_id),
    'promedio_ticket', COALESCE((SELECT AVG(monto) FROM pagos WHERE fecha >= v_month_start AND fecha <= v_month_end AND estado = 'confirmado' AND empresa_id = p_empresa_id), 0),
    'duplicados_hoy', (SELECT COUNT(*) FROM (SELECT banco, referencia FROM pagos WHERE empresa_id = p_empresa_id GROUP BY banco, referencia HAVING COUNT(*) > 1) dup),
    'transacciones_editadas', (SELECT COUNT(*) FROM audit_log WHERE accion = 'editar' AND empresa_id = p_empresa_id AND creado_en >= v_month_start::timestamptz),
    'transacciones_anuladas', (SELECT COUNT(*) FROM pagos WHERE estado = 'anulado' AND empresa_id = p_empresa_id AND actualizado_en >= v_month_start::timestamptz),
    'pendientes_revision', (SELECT COUNT(*) FROM pagos WHERE estado = 'pendiente' AND empresa_id = p_empresa_id),
    'sin_comprobante_total', (SELECT COUNT(*) FROM pagos WHERE empresa_id = p_empresa_id AND (imagen_uri IS NULL OR imagen_uri LIKE 'capacitor://%')),
    'meta_mes', (SELECT meta_ingresos FROM metas_mensuales WHERE mes = v_mes_actual AND empresa_id = p_empresa_id)
  ) INTO result;
  RETURN result;
END;
$function$;
