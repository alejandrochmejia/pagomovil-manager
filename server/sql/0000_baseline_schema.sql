CREATE OR REPLACE FUNCTION public.get_pagos_duplicados(p_empresa_id bigint)
 RETURNS SETOF pagos LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $function$
  SELECT p.*
  FROM pagos p
  JOIN (
    SELECT banco, referencia
    FROM pagos
    WHERE empresa_id = p_empresa_id
    GROUP BY banco, referencia
    HAVING COUNT(*) > 1
  ) g ON p.banco = g.banco AND p.referencia = g.referencia
  WHERE p.empresa_id = p_empresa_id
  ORDER BY p.banco, p.referencia, p.fecha DESC, p.id DESC;
$function$;

